import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
const migrations=readdirSync('drizzle').filter(n=>n.endsWith('.sql')).sort();
const db=new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
let now=1800000000;db.function('unixepoch',()=>now);
for(const name of migrations.slice(0,5))db.exec(readFileSync('drizzle/'+name,'utf8'));
db.prepare("INSERT INTO rounds(id,owner,kind,opens,closes,title) VALUES('existing','old-owner','weekly',?,?, 'Existing round')").run(now-100,now-1);
db.exec("INSERT INTO profiles(id,premium_until,frame,nickname,nickname_key) VALUES('old-driver',1800005000,'neon','OldDriver','olddriver')");
db.prepare("INSERT INTO entries(id,round_id,owner,name,description,media,created) VALUES('old-entry','existing','old-driver','Existing car','Keep this','entries/old-photo',?)").run(now-90);
db.prepare("INSERT INTO votes(entry_id,voter,created,value) VALUES('old-entry','old-voter',?,1)").run(now-50);
db.prepare("INSERT INTO sessions(id,user_id,expires) VALUES('old-session','old-driver',?)").run(now+500);
const profile=db.prepare("SELECT * FROM profiles WHERE id='old-driver'").get();
for(const name of migrations.slice(5))db.exec(readFileSync('drizzle/'+name,'utf8'));
assert.deepEqual(db.prepare("SELECT * FROM profiles WHERE id='old-driver'").get(),profile);
assert.equal(db.prepare("SELECT media FROM entries WHERE id='old-entry'").get().media,'entries/old-photo');
assert.equal(db.prepare("SELECT winner_id FROM round_outcomes WHERE round_id='existing'").get().winner_id,'old-entry');
assert.equal(db.prepare("SELECT count(*) n FROM votes WHERE entry_id='old-entry'").get().n,1);
assert.equal(db.prepare("SELECT user_id FROM sessions WHERE id='old-session'").get().user_id,'old-driver');
assert.equal(db.prepare('PRAGMA foreign_key_check').all().length,0);
for(const name of ['motors','commerce_orders','organizers','deleted_accounts','media_deletion_jobs'])assert(db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name=?").get(name));
db.close();
console.log('PASS: upgrading the existing five-migration GitHub database preserves profiles, Premium, photos, votes, winners and sessions; all migrations and foreign keys pass.');
